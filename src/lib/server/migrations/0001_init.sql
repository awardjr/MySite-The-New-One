CREATE TABLE home (
	id INTEGER PRIMARY KEY CHECK (id = 1),
	name TEXT NOT NULL DEFAULT '',
	tagline TEXT NOT NULL DEFAULT '',
	photo_src TEXT NOT NULL DEFAULT '',
	intro_paragraphs TEXT NOT NULL DEFAULT '[]',
	featured_posts TEXT NOT NULL DEFAULT '[]',
	featured_works TEXT NOT NULL DEFAULT '[]'
);

CREATE TABLE links (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	label TEXT NOT NULL,
	href TEXT NOT NULL,
	icon TEXT NOT NULL,
	description TEXT NOT NULL DEFAULT '',
	sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE works (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	title TEXT NOT NULL,
	description TEXT NOT NULL,
	image TEXT NOT NULL DEFAULT '',
	link TEXT NOT NULL DEFAULT '',
	platforms TEXT NOT NULL DEFAULT '[]',
	sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE press (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	outlet TEXT NOT NULL DEFAULT '',
	title TEXT NOT NULL,
	summary TEXT NOT NULL,
	href TEXT NOT NULL,
	date TEXT NOT NULL DEFAULT '',
	sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE pinball_machines (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	name TEXT NOT NULL,
	image TEXT NOT NULL DEFAULT '',
	high_score TEXT NOT NULL DEFAULT '',
	mode_scores TEXT NOT NULL DEFAULT '[]',
	sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE posts (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	slug TEXT NOT NULL UNIQUE,
	title TEXT NOT NULL,
	date TEXT NOT NULL,
	image TEXT NOT NULL DEFAULT '',
	preview TEXT NOT NULL DEFAULT '',
	content TEXT NOT NULL DEFAULT '',
	draft INTEGER NOT NULL DEFAULT 0,
	sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE page_headlines (
	page TEXT PRIMARY KEY,
	headline TEXT NOT NULL DEFAULT '',
	subtitle TEXT NOT NULL DEFAULT ''
);
